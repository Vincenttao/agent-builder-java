import { test, expect } from '@playwright/test';
test('AC-01/02 部分: 登录、保存、刷新恢复、更新与运行阻塞', async ({ page }) => {
  const token = process.env.LOCAL_BOOTSTRAP_TOKEN;
  if (!token) throw new Error('LOCAL_BOOTSTRAP_TOKEN required for real browser test');
  await page.goto('/');
  await page.getByLabel('本地访问令牌').fill(token);
  await page.getByRole('button', { name: '进入工作台' }).click();
  await expect(page.getByRole('heading', { name: '需求工作台' })).toBeVisible();
  const environment = await (await page.request.get('/api/environment')).json();
  expect(environment).toMatchObject({ model: 'not_configured', canSaveDraft: true, canRun: false });
  await page.getByRole('button', { name: '新建草稿' }).click();
  const name = `余额助手-${Date.now()}`;
  await page.getByLabel('Agent 名称').fill(name);
  await page.getByRole('textbox', { name: /目标使用者/ }).fill('银行 AI 平台开发人员');
  await page.getByRole('textbox', { name: /业务目标/ }).fill('查询余额，不进行交易');
  await page.getByRole('textbox', { name: /交付内容/ }).fill('账户余额与币种');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await expect(page.getByText('已保存 · 修订 1', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('combobox', { name: '选择项目' }).selectOption({ label: `${name} · r1` });
  await expect(page.getByRole('textbox', { name: /业务目标/ })).toHaveValue('查询余额，不进行交易');
  await page.getByRole('textbox', { name: /交付内容/ }).fill('余额、币种和查询时间');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await expect(page.getByText('已保存 · 修订 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '检查运行条件' }).click();
  await expect(page.getByRole('alert')).toContainText('请先确认需求、固定测试版本');
  const draftsResponse = await page.request.get('/api/drafts', { headers: { origin: process.env.APP_ORIGIN! } });
  const draft = (await draftsResponse.json()).items.find((item: { name: string }) => item.name === name);
  expect(draft).toBeTruthy();
  const csrf = await (await page.request.get('/api/auth/session', { headers: { origin: process.env.APP_ORIGIN! } })).json();
  const confirmedDraft = { name: draft.name, brief: Object.fromEntries(Object.entries(draft.brief).map(([key, value]) => [key, { ...(value as object), confirmed: true }])), expectedRevision: draft.revision };
  const updated = await page.request.put(`/api/drafts/${draft.id}`, { headers: { origin: process.env.APP_ORIGIN!, 'x-csrf-token': csrf.csrfToken }, data: confirmedDraft });
  expect(updated.status()).toBe(200);
  const snapshot = await page.request.post(`/api/drafts/${draft.id}/snapshots`, { headers: { origin: process.env.APP_ORIGIN!, 'x-csrf-token': csrf.csrfToken }, data: { expectedRevision: draft.revision + 1, assembly: { agentType: 'DeepAgent', systemPrompt: '查询设备状态；缺少编号时先追问。', maxIterations: 4, railIds: ['audit@1', 'tool-allowlist@1'], toolIds: ['equipment-status@1'] } } });
  expect(snapshot.status()).toBe(201);
  const fixed = await snapshot.json();
  const blocked = await page.request.post(`/api/snapshots/${fixed.id}/runs`, { headers: { origin: process.env.APP_ORIGIN!, 'x-csrf-token': csrf.csrfToken }, data: { clientRequestId: crypto.randomUUID(), input: '请查询 PUMP-001 的状态。' } });
  expect(blocked.status()).toBe(409);
  expect(await blocked.json()).toMatchObject({ code: 'ENVIRONMENT_BLOCKED' });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileWidth = await page.evaluate(() => ({ viewport: window.innerWidth, document: document.documentElement.scrollWidth, offenders: [...document.querySelectorAll('body *')].filter(element => element.getBoundingClientRect().right > window.innerWidth + 1).slice(0, 12).map(element => ({ tag: element.tagName, className: typeof element.className === 'string' ? element.className : '', right: Math.round(element.getBoundingClientRect().right), width: Math.round(element.getBoundingClientRect().width) })) }));
  expect(mobileWidth.document, JSON.stringify(mobileWidth)).toBeLessThanOrEqual(mobileWidth.viewport);
  await page.screenshot({ path: 'test-results/workbench-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/workbench-desktop.png', fullPage: true });
});
