import { test, expect } from '@playwright/test';
test('AC-01/02 部分: 登录、保存、刷新恢复、更新与运行阻塞', async ({ page }) => {
  const token = process.env.LOCAL_BOOTSTRAP_TOKEN;
  if (!token) throw new Error('LOCAL_BOOTSTRAP_TOKEN required for real browser test');
  await page.goto('/');
  await page.getByLabel('本地访问令牌').fill(token);
  await page.getByRole('button', { name: '进入工作台' }).click();
  await expect(page.getByRole('heading', { name: '需求工作台' })).toBeVisible();
  await page.getByRole('button', { name: '新建草稿' }).click();
  const name = `余额助手-${Date.now()}`;
  await page.getByLabel('Agent 名称').fill(name);
  await page.getByRole('textbox', { name: /目标使用者/ }).fill('银行 AI 平台开发人员');
  await page.getByRole('textbox', { name: /业务目标/ }).fill('查询余额，不进行交易');
  await page.getByRole('textbox', { name: /交付内容/ }).fill('账户余额与币种');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await expect(page.getByText('已保存 · 修订 1', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name, exact: true }).click();
  await expect(page.getByRole('textbox', { name: /业务目标/ })).toHaveValue('查询余额，不进行交易');
  await page.getByRole('textbox', { name: /交付内容/ }).fill('余额、币种和查询时间');
  await page.getByRole('button', { name: '保存草稿' }).click();
  await expect(page.getByText('已保存 · 修订 2', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '检查运行条件' }).click();
  await expect(page.getByRole('alert')).toContainText(/Java Runtime 尚未接入|固定测试版本/);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/workbench-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/workbench-desktop.png', fullPage: true });
});
