import {test,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {equipmentSample as sample} from '../../apps/web/src/prebuilt-sample.js';
import type {ValidationExecution,ValidationReport} from '../../packages/contracts/src/validations.js';
import type {ReleaseOverview} from '../../packages/contracts/src/releases.js';

test('prebuilt sample: real validation, timeout evidence, release and browser conversation',async({page})=>{
  test.skip(process.env.RUN_LIVE_E2E!=='1','Explicit live opt-in required');
  const root='test-results/rp-01';await mkdir(root,{recursive:true});
  const proof:Record<string,unknown>={startedAt:new Date().toISOString(),sample,status:'running'};
  const mutations:string[]=[];const pageErrors:string[]=[];
  page.on('pageerror',error=>pageErrors.push(error.message));
  page.on('request',request=>{if(request.method()==='POST')mutations.push(new URL(request.url()).pathname);});
  try {
    await page.goto('/');await page.getByLabel('本地访问令牌').fill(process.env.LOCAL_BOOTSTRAP_TOKEN!);
    await page.getByRole('button',{name:'进入工作台',exact:true}).click();
    await page.getByRole('button',{name:'体验预构建样例',exact:true}).click();
    await expect(page.getByText('本次复用已有产物，未调用开发 Agent',{exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'已确认的样例需求'})).toBeVisible();
    await expect(page.getByLabel('业务目标',{exact:true})).toHaveAttribute('readonly','');
    const get=async<T>(path:string):Promise<T>=>{const response=await page.request.get(path);expect(response.ok(),path).toBe(true);return response.json() as Promise<T>;};
    proof.beforeCandidate=await get(`/api/candidates/${sample.candidateId}`);
    const previous=await get<{items:ValidationExecution[]}>(`/api/snapshots/${sample.snapshotId}/validations`);
    await page.getByRole('tab',{name:/环境与装配/}).click();
    await expect(page.getByText('get_equipment',{exact:true})).toBeVisible();
    await expect(page.getByText('未装载独立 Skill；使用固定 Agent 指令。',{exact:true})).toBeVisible();
    await expect(page.getByText('tool-allowlist',{exact:true})).toBeVisible();
    await page.screenshot({path:`${root}/assembly-desktop.png`,fullPage:true});
    await page.getByRole('tab',{name:/发布与对话/}).click();
    await expect(page.getByRole('button',{name:'发布此验证版本',exact:true})).toBeDisabled();
    proof.publishBeforeReviewBlocked=true;
    await page.getByRole('tab',{name:/测试与证据/}).click();
    await expect(page.getByRole('button',{name:'启动双角色开发',exact:true})).toHaveCount(0);
    await expect(page.getByLabel('自动验收目标')).toHaveValue(sample.candidateId);
    await expect(page.getByLabel('自动验收目标')).toBeDisabled();
    await expect(page.getByLabel('使用验收基线')).toHaveValue(sample.baselineId);
    const resumeValidation=process.env.RP01_VALIDATION_ID;
    if(!resumeValidation)await page.getByRole('button',{name:'运行验收用例',exact:true}).click();
    console.log(resumeValidation?'RP-01: observing existing validation':'RP-01: browser started validation');
    let validation:ValidationExecution|undefined;
    await expect.poll(async()=>{
      const list=await get<{items:ValidationExecution[]}>(`/api/snapshots/${sample.snapshotId}/validations`);
      validation=list.items.find(item=>resumeValidation?item.id===resumeValidation:!previous.items.some(old=>old.id===item.id));
      if(validation)proof.validationId=validation.id;
      return validation?.status;
    },{timeout:360_000,intervals:[2000]}).toBe('completed');
    const report=await get<ValidationReport>(`/api/validations/${validation!.id}/report`);proof.report=report;
    proof.caseEvidence=await Promise.all(report.cases.map(c=>get(`/api/validations/${report.executionId}/evidence/${c.evidenceId}`)));
    expect(report.verdict,JSON.stringify(report.cases)).toBe('passed');
    expect(report.binding.candidate?.id).toBe(sample.candidateId);
    expect(report.binding.artifactDigest).toBe(sample.artifactDigest);
    expect(report.binding.modelProfile.executionMode).toBe('live-mock');
    if(resumeValidation)await page.getByLabel('验证记录').selectOption(resumeValidation);
    expect(report.cases.map(c=>c.caseId)).toEqual(['TC-001','TC-002','TC-003']);
    const failure=report.cases.find(c=>c.caseId==='TC-003')!;
    expect(failure.assertions.find(a=>a.ruleId==='tool-error-evidence')?.status).toBe('passed');
    expect(failure.assertions.find(a=>a.ruleId==='failure-output-no-facts')?.status).toBe('passed');
    await expect(page.getByTestId('validation-status')).toHaveText('通过');
    await page.getByText('TC-003 · 通过',{exact:true}).click();
    await page.getByRole('button',{name:'查看证据 TC-003',exact:true}).click();
    await expect(page.getByTestId('validation-evidence')).toBeVisible();
    await page.screenshot({path:`${root}/timeout-evidence.png`,fullPage:true});
    await page.getByRole('tab',{name:/发布与对话/}).click();
    await page.getByLabel('我已审阅验收报告，同意切换演示入口').check();
    await page.getByRole('button',{name:'发布此验证版本',exact:true}).click();
    await expect(page.getByTestId('release-status')).toHaveText('发布成功',{timeout:120_000});
    const overview=await get<ReleaseOverview>(`/api/drafts/${sample.draftId}/releases`);proof.release=overview;
    const version=overview.versions.find(v=>v.id===overview.pointer?.versionId)!;
    expect(version.reference.binding.candidate?.id).toBe(sample.candidateId);
    expect(version.validationId).toBe(report.executionId);
    await page.getByLabel('模拟业务身份').selectOption('U1002');
    await page.getByRole('button',{name:'进入模拟 App',exact:true}).click();
    await page.getByLabel('业务请求',{exact:true}).fill('查询 PUMP-001 的状态、温度和来源，输出设备报告。');
    await page.getByRole('button',{name:'发送业务请求',exact:true}).click();
    await expect(page.getByTestId('demo-request-status')).toHaveText('已完成',{timeout:120_000});
    await expect(page.getByTestId('demo-result')).toContainText('86');
    await page.getByText('演示详情与证据',{exact:true}).click();
    const business=JSON.parse((await page.getByTestId('demo-evidence').textContent())!);proof.business=business;
    expect(business.agentVersion).toBe(version.id);
    expect(business.externalEvidence).toHaveLength(1);
    expect(JSON.stringify(business.externalEvidence)).toContain('PUMP-001');
    expect(JSON.stringify(business.externalEvidence)).toContain('86');
    await page.screenshot({path:`${root}/dialog-desktop.png`,fullPage:true});
    await page.setViewportSize({width:390,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:`${root}/dialog-mobile.png`,fullPage:true});
    proof.afterCandidate=await get(`/api/candidates/${sample.candidateId}`);
    expect(proof.afterCandidate).toEqual(proof.beforeCandidate);
    expect(mutations.some(path=>path.endsWith('/development')||path==='/api/candidates'||path.endsWith('/snapshots'))).toBe(false);
    expect(pageErrors).toEqual([]);proof.status='passed';
    console.log('RP-01: published sample and verified real browser business request');
  } catch(error){proof.status='failed';proof.error=error instanceof Error?error.message:String(error);throw error;}
  finally {proof.mutations=mutations;proof.pageErrors=pageErrors;proof.finishedAt=new Date().toISOString();await writeFile(`${root}/live-proof.json`,JSON.stringify(proof,null,2));}
});

test('prebuilt sample restores published evidence and preserves the normal workbench',async({page})=>{
  test.skip(process.env.RUN_DEMO_RESTORE!=='1','Requires an already verified and published sample; does not invoke the model');
  await page.goto('/?demo=equipment');await page.getByLabel('本地访问令牌').fill(process.env.LOCAL_BOOTSTRAP_TOKEN!);
  await page.getByRole('button',{name:'进入工作台',exact:true}).click();
  await page.reload();await page.getByRole('tab',{name:/测试与证据/}).click();
  await expect(page.getByTestId('validation-status')).toHaveText('通过');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('tab',{name:/发布与对话/}).click();
  const active=await page.getByRole('tab',{name:/发布与对话/}).boundingBox();
  expect(active && active.x>=0 && active.x+active.width<=390).toBe(true);
  await page.getByRole('button',{name:'进入模拟 App',exact:true}).click();
  await expect(page.getByLabel('业务请求',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/rp-01/restored-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'返回开发工作台',exact:true}).click();
  await expect(page.getByRole('heading',{name:'需求工作台',exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'选择项目'}).selectOption(sample.draftId);
  await page.getByRole('tab',{name:/开发与测试/}).click();
  await page.getByLabel('当前测试版本',{exact:true}).selectOption(sample.snapshotId);
  await expect(page.getByRole('button',{name:'启动双角色开发',exact:true})).toBeVisible();
  await expect(page.getByLabel('自动验收目标')).toBeEnabled();
});
