import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { Pool } from '../../apps/server/src/db/pool.js';
import { migrate } from '../../apps/server/src/db/migrations.js';
import { DraftService } from '../../apps/server/src/drafts/application/draft-service.js';
import { PostgresDraftRepository } from '../../apps/server/src/drafts/adapters/postgres-drafts.js';
import { PostgresSnapshotRepository } from '../../apps/server/src/snapshots/adapters/postgres-snapshots.js';
import { SnapshotService } from '../../apps/server/src/snapshots/application/snapshot-service.js';
import { BaselineService } from '../../apps/server/src/acceptance/application/baseline-service.js';
import { createApp } from '../../apps/server/src/app.js';
import { draftInput } from '../support/fixtures.js';
import { contentDigest } from '../../apps/server/src/snapshots/domain/assembly.js';
import { workOrderAssembly } from '../../packages/contracts/src/equipment-template.js';

const url = process.env.TEST_DATABASE_URL ?? 'postgres://builder_test:local-test-only@127.0.0.1:15432/builder_test';
const schema = `it_baselines_${randomUUID().replaceAll('-', '')}`;
const admin = new Pool({ connectionString: url }); const pool = new Pool({ connectionString: url, options: `-c search_path=${schema}` });
const clock = { now: () => new Date().toISOString() }; const ids = { next: randomUUID };
const drafts = new DraftService(new PostgresDraftRepository(pool), clock, ids);
const snapshots = new SnapshotService(drafts, new PostgresSnapshotRepository(pool), clock, ids);
const baselines = new BaselineService(pool, clock, ids);
const origin = 'http://127.0.0.1:8080'; const token = 'baseline-test-bootstrap-0123456789012';
const app = createApp({ drafts, baselines, bootstrapToken: token, origin, now: clock.now, modelConfigured: false, databaseReady: async () => true });
const confirmedInput = { ...draftInput, name: '设备工单助手', brief: { ...draftInput.brief, goal: { value: '查询设备并申请工单', source: 'user' as const, confirmed: true }, output: { value: '设备事实与经确认的模拟工单', source: 'user' as const, confirmed: true } } };
const input = { expectedRevision: 1, templateId: 'equipment-workorder@1', confirmed: true, expectedDigest: '' };
const reviewed = async (id: string, value = input) => ({ ...value, expectedDigest: (await baselines.preview(id, value.templateId)).digest });
beforeAll(async () => { await admin.query(`CREATE SCHEMA "${schema}"`); await migrate(pool); });
afterAll(async () => { await app.close(); await pool.end(); await admin.query(`DROP SCHEMA "${schema}" CASCADE`); await admin.end(); });
describe('independent, user-confirmed project acceptance baseline', () => {
  it('preserves historical workorder rules but requires explicit confirmation of current rules before reuse',async()=>{
    const draft=await drafts.create(confirmedInput),preview=await baselines.preview(draft.id,input.templateId);
    const content={...preview.content,rulesVersion:'equipment-assertions@1' as const},digest=contentDigest(content);
    const old={id:randomUUID(),draftId:draft.id,draftRevision:1,digest,confirmedAt:clock.now(),confirmedBy:'local-operator',content};
    await pool.query('INSERT INTO acceptance_baselines(id,draft_id,draft_revision,digest,record) VALUES ($1,$2,$3,$4,$5)',[old.id,draft.id,1,digest,old]);
    const snapshot=await snapshots.create(draft.id,{expectedRevision:1,assembly:workOrderAssembly()});
    await expect(baselines.assertTarget(old.id,snapshot)).rejects.toMatchObject({code:'BASELINE_RULES_CHANGED'});
    expect(await baselines.get(old.id)).toEqual(old);
    const current=await baselines.confirm(draft.id,{...input,expectedDigest:preview.digest});
    expect(current.digest).not.toBe(old.digest);expect(current.content.rulesVersion).toBe('equipment-workorder-assertions@2');
    await expect(baselines.assertTarget(current.id,snapshot)).resolves.toEqual(current);
    expect(await baselines.list(draft.id)).toHaveLength(2);
  });
  it('provides a reviewable preview and rejects confirmation of a different reviewed digest', async () => {
    const draft = await drafts.create(confirmedInput);
    const preview = await baselines.preview(draft.id, input.templateId);
    expect(preview.content.cases).toHaveLength(8); expect(await baselines.list(draft.id)).toEqual([]);
    await expect(baselines.confirm(draft.id, { ...input, expectedDigest: 'f'.repeat(64) })).rejects.toMatchObject({ code: 'BASELINE_PREVIEW_MISMATCH' });
    expect((await baselines.confirm(draft.id, { ...input, expectedDigest: preview.digest })).digest).toBe(preview.digest);
  });
  it('requires confirmed requirements and explicit baseline confirmation', async () => {
    const draft = await drafts.create(draftInput);
    await expect(baselines.confirm(draft.id, input)).rejects.toMatchObject({ code: 'BRIEF_NOT_CONFIRMED' });
    const ready = await drafts.create(confirmedInput);
    await expect(baselines.confirm(ready.id, { ...input, confirmed: false })).rejects.toMatchObject({ code: 'BASELINE_CONFIRMATION_REQUIRED' });
    await expect(baselines.confirm(ready.id, { ...input, expectedRevision: 2 })).rejects.toMatchObject({ code: 'REVISION_CONFLICT' });
  });
  it('freezes all required scenarios, deduplicates confirmation and rejects database mutation', async () => {
    const draft = await drafts.create(confirmedInput);
    const payload = await reviewed(draft.id);
    const [a, b] = await Promise.all([baselines.confirm(draft.id, payload), baselines.confirm(draft.id, payload)]);
    expect(a.id).toBe(b.id); expect(a.digest).toMatch(/^[a-f0-9]{64}$/);
    expect(a.content.cases.map(c => c.scenario)).toEqual(['equipment-normal','equipment-missing-id','equipment-tool-failure','workorder-approve','workorder-reject','workorder-expired','workorder-changed-arguments','workorder-write-timeout']);
    expect(a.content.requirements.every(r => /^BR-\d{3}$/.test(r.id))).toBe(true);
    expect(a.content.cases.every(c => c.required && c.assertions.length > 0 && c.requirementIds.length > 0)).toBe(true);
    expect(a.content.cases.every(c => /^TC-\d{3}$/.test(c.id))).toBe(true);
    await expect(pool.query("UPDATE acceptance_baselines SET record=record-'digest' WHERE id=$1", [a.id])).rejects.toThrow('immutable');
    await expect(pool.query('DELETE FROM acceptance_baselines WHERE id=$1', [a.id])).rejects.toThrow('immutable');
  });
  it('a code/config repair can reuse a baseline; changed requirements cannot reuse it', async () => {
    const draft = await drafts.create(confirmedInput); const baseline = await baselines.confirm(draft.id, await reviewed(draft.id));
    const assembly = { agentType: 'DeepAgent', systemPrompt: '第一次实现', maxIterations: 5, railIds: ['audit@1','tool-allowlist@1','write-confirm@1'], toolIds: ['equipment-status@1','work-order-create@1'] };
    const a = await snapshots.create(draft.id, { expectedRevision: 1, assembly });
    const repaired = await snapshots.create(draft.id, { expectedRevision: 1, assembly: { ...assembly, systemPrompt: '修复后的实现' } });
    expect(a.digest).not.toBe(repaired.digest);
    await expect(baselines.assertTarget(baseline.id, a)).resolves.toEqual(baseline);
    await expect(baselines.assertTarget(baseline.id, repaired)).resolves.toEqual(baseline);
    await drafts.update(draft.id, { ...confirmedInput, expectedRevision: 1, brief: { ...confirmedInput.brief, goal: { value: '新增目标', source: 'user', confirmed: true } } });
    const changed = await snapshots.create(draft.id, { expectedRevision: 2, assembly });
    await expect(baselines.assertTarget(baseline.id, changed)).rejects.toMatchObject({ code: 'BASELINE_TARGET_MISMATCH' });
    const next = await baselines.confirm(draft.id, await reviewed(draft.id, { ...input, expectedRevision: 2 })); expect(next.digest).not.toBe(baseline.digest);
    expect(await baselines.get(baseline.id)).toEqual(baseline);
  });
  it('read-only acceptance cannot authorize a snapshot that binds a write tool', async () => {
    const draft = await drafts.create(confirmedInput); const baseline = await baselines.confirm(draft.id, await reviewed(draft.id, { ...input, templateId: 'equipment-read@1' }));
    const target = await snapshots.create(draft.id, { expectedRevision: 1, assembly: { agentType: 'DeepAgent', systemPrompt: '创建工单', maxIterations: 5, railIds: ['audit@1','tool-allowlist@1','write-confirm@1'], toolIds: ['equipment-status@1','work-order-create@1'] } });
    await expect(baselines.assertTarget(baseline.id, target)).rejects.toMatchObject({ code: 'BASELINE_COVERAGE_MISMATCH' });
  });
  it('management API rejects caller-supplied reduced cases, anonymous confirmation and confirmation without CSRF', async () => {
    const draft = await drafts.create(confirmedInput); const path = `/api/drafts/${draft.id}/baselines`;
    expect((await app.inject({ method: 'POST', url: path, headers: { origin }, payload: input })).statusCode).toBe(401);
    const login = await app.inject({ method: 'POST', url: '/api/auth/session', headers: { origin }, payload: { token } });
    const headers = { origin, cookie: login.headers['set-cookie']!.toString().split(';')[0]!, 'x-csrf-token': login.json().csrfToken as string };
    expect((await app.inject({ method: 'POST', url: path, headers: { origin, cookie: headers.cookie }, payload: input })).statusCode).toBe(403);
    expect((await app.inject({ method: 'POST', url: path, headers, payload: { ...input, cases: [] } })).statusCode).toBe(400);
    const preview = await app.inject({ url: `/api/drafts/${draft.id}/baseline-preview?templateId=${input.templateId}`, headers }); expect(preview.statusCode).toBe(200);
    const response = await app.inject({ method: 'POST', url: path, headers, payload: { ...input, expectedDigest: preview.json().digest } }); expect(response.statusCode, response.body).toBe(201);
    expect((await app.inject({ url: `/api/baselines/${response.json().id}`, headers })).json()).toEqual(response.json());
    expect((await app.inject({ url: path, headers })).json().items).toHaveLength(1);
  });
});
