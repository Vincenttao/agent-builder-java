import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdtempSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createWorkbench, readTree } from '../workbench-server/app.js';
import { navigate } from './pc-navigation.js';
test('restored desktop design: interactive graph, saved previews, capabilities, checks, candidates and platform guidance', async (t) => {
    const root = mkdtempSync(join(tmpdir(), 'workbench-parity-')), wb = createWorkbench({ root, templateFiles: readTree('templates/moa') });
    const release = wb.store.publish('moa-platform', 'platform', '1.0.0'), p = wb.store.createApplication(release.id, '综合业务演示', 'application');
    const files = readTree('examples/commerce-wealth');
    wb.store.save(p.id, 'application', p.head, files);
    const server = wb.app.listen(0, '127.0.0.1');
    await new Promise<void>(r => server.once('listening', r));
    const browser = await chromium.launch({ headless: true });
    t.after(async () => { await browser.close(); await wb.close(); await new Promise<void>(r => server.close(() => r())); wb.store.close(); rmSync(root, { recursive: true, force: true }); });
    const address = server.address();
    assert.ok(address && typeof address !== 'string');
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(6000);
    const errors: string[] = [];
    let executions = 0;
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => { if (r.method() !== 'GET' && /\/runs|\/jobs|\/messages/.test(r.url()))
        executions++; });
    await page.goto('http://127.0.0.1:' + address.port);
    await page.getByRole('button', { name: '进入工程', exact: true }).click();
    assert.deepEqual(await page.getByRole('navigation', { name: '当前工程导航' }).getByRole('button').allTextContents(), ['概览', '开发', '测试', '运行记录', '版本与发布']);
    await navigate(page, '处理流程');
    assert.equal(await page.locator('.map-node').count(), 7);
    assert.equal(await page.getByRole('navigation', { name: '编排内容' }).getByRole('button').count(), 5);
    await page.locator('[data-design-example="0"]').click();
    assert.equal(await page.locator('.map-node.is-path').getAttribute('data-design-node'), 'skill');
    await page.locator('[data-design-node="handoff"]').click();
    assert.equal(await page.locator('.map-node.is-path').getAttribute('data-design-node'), 'skill');
    assert.equal(await page.locator('.map-inspector').getAttribute('data-map-inspector'), 'handoff');
    await page.locator('#flow-query').fill('没有匹配的业务');
    assert.equal(await page.locator('.map-node.is-path').count(), 0);
    await page.getByRole('button', { name: '查看路径', exact: true }).click();
    assert.equal(await page.locator('.map-node.is-path').getAttribute('data-design-node'), 'clarify');
    await page.reload();await page.locator('#flow-query').waitFor();assert.equal(await page.locator('#flow-query').inputValue(),'没有匹配的业务');assert.equal(await page.locator('.map-node.is-path').getAttribute('data-design-node'),'clarify');
    await page.locator('#flow-mode').selectOption('branches');
    await page.locator('#flow-branch').selectOption('DELEGATE');
    await page.getByRole('button', { name: '查看路径', exact: true }).click();
    assert.equal(await page.locator('.map-node.is-path').getAttribute('data-design-node'), 'blocked');
    for (const width of [1280, 1440, 1920]) {
        await page.setViewportSize({ width, height: 1000 });
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'graph overflow ' + width);
    }
    mkdirSync('test-results/demo-restoration-20261025', { recursive: true });
    await page.screenshot({ path: 'test-results/demo-restoration-20261025/graph.png', fullPage: true });
    await page.locator('[data-design-section="skills"]').click();
    await page.getByRole('button', { name: 'wealth · 查看过程', exact: true }).click();
    assert.equal(await page.locator('.skill-process-node').count(), 8);assert.ok(await page.locator('.skill-diagram svg path[d*="H570"]').count()>0,'skip edges must route around intermediate nodes');
    assert.ok(await page.getByText('资金不足：询问是否转账', { exact: true }).count());
    await page.screenshot({ path: 'test-results/demo-restoration-20261025/wealth-flow.png', fullPage: true });
    await page.locator('[data-design-section="handoff"]').click();
    assert.equal(await page.locator('.policy-question').count(), 3);
    await page.locator('[data-design-section="preview"]').click();
    await page.locator('#rule-scenario').selectOption('two');
    await page.getByRole('button', { name: '预演规则', exact: true }).click();
    await page.getByText('B保持原状态，不调用C', { exact: true }).waitFor();
    await page.locator('#rule-scenario').selectOption('pending');
    await page.getByRole('button', { name: '预演规则', exact: true }).click();
    await page.getByText('请先配置有效的范围外接管目标。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '能力', exact: true }).click();
    await page.locator('[data-cap-filter="operation"]').click();
    assert.equal(await page.locator('[data-cap-select]').count(), 8);
    await page.locator('[data-cap-select="transfer"]').click();
    await page.getByText('写操作 · 必须确认', { exact: true }).waitFor();
    await page.getByRole('button', { name: '测试', exact: true }).click();
    await page.getByRole('button', { name: '检查保存版本', exact: true }).click();
    await page.getByText('结构检查通过；业务未验证', { exact: false }).waitFor();
    await page.getByRole('button', { name: '保存源码技术候选', exact: true }).click();
    await page.locator('.candidate-card').waitFor();
    assert.equal((wb.store.db.prepare('SELECT count(*) n FROM design_candidates').get() as {n:number}).n, 1);
    await navigate(page, '业务配置');
    await page.getByLabel('自己负责的业务').fill('修改后待检查的业务');
    await page.getByRole('button', { name: '保存所有修改', exact: true }).click();
    await page.getByText('已提交工程版本', { exact: true }).waitFor();
    await page.getByRole('button', { name: '测试', exact: true }).click();
    await page.getByText('旧版本候选', { exact: false }).waitFor();
    assert.equal(await page.getByRole('button', { name: '保存源码技术候选', exact: true }).isDisabled(), true);
    await page.locator('#identity').selectOption('platform');
    await page.locator('.project-card').filter({ has: page.getByRole('heading', { name: 'MOA 开发模板', exact: true }) }).getByRole('button', { name: '进入工程', exact: true }).click();
    await page.locator('#global-nav').getByRole('button', { name: '开发 Skill', exact: true }).click();
    await page.getByRole('heading', { name: '范式开发 Skill', exact: true }).waitFor();
    assert.ok(await page.locator('.skill-description').count() > 0);
    await page.locator('#global-nav').getByRole('button', { name: '工程活动', exact: true }).click();
    await page.locator('.candidate-card').first().waitFor();
    await page.screenshot({ path: 'test-results/demo-restoration-20261025/platform.png', fullPage: true });
    assert.equal(executions, 0);
    assert.deepEqual(errors, []);
});
