import {navigate} from './pc-navigation.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createWorkbench,readTree} from '../workbench-server/app.js';

test('PC entry uses real role, release, empty application, independent drafts and Git saves',async t=>{
 const root=mkdtempSync(join(tmpdir(),'workbench-pc-'));
 const workbench=createWorkbench({root,templateFiles:readTree(resolve('templates/moa'))});
 const server=workbench.app.listen(0,'127.0.0.1');await new Promise<void>(r=>server.once('listening',r));
 const browser=await chromium.launch({headless:true});
 t.after(async()=>{await browser.close();await workbench.close();await new Promise<void>(r=>server.close(()=>r()));workbench.store.close();rmSync(root,{recursive:true,force:true});});
 const address=server.address();assert.ok(address&&typeof address!=='string');
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 await page.addInitScript(()=>{localStorage.setItem('openjiuwen-workbench-v2-demo-99','old mock');localStorage.setItem('unrelated-user-data','preserve');});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${address.port}`);
 await page.getByText('尚无已发行模板。',{exact:false}).waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('openjiuwen-workbench-v2-demo-99')),null);
 assert.equal(await page.evaluate(()=>localStorage.getItem('unrelated-user-data')),'preserve');
 await page.locator('#identity').selectOption('platform');
 await page.getByRole('button',{name:'进入工程'}).click();
 await page.getByRole('button',{name:'模板发行',exact:true}).click();
 await page.getByLabel('版本号').fill('1.0.0');
 await page.getByRole('button',{name:'发行模板',exact:true}).click();
 await page.getByText('模板版本已发行',{exact:true}).waitFor();
 await page.locator('#identity').selectOption('application');
 await page.getByLabel('应用名称').fill('i豆福利助手');
 await page.getByRole('button',{name:'创建空白应用'}).click();
 await page.getByRole('heading',{name:'i豆福利助手',exact:true}).waitFor();
 const apps=workbench.store.list('application');assert.equal(apps.length,1);
 assert.deepEqual(workbench.store.definition(apps[0].id,'application').skills,[]);
 await navigate(page,'文件与指令');
 await page.locator('#editor').fill('这是尚未保存的应用指令。');
 await page.locator('#identity').selectOption('platform');
 await page.getByRole('button',{name:'查看诊断'}).click();
 await navigate(page,'文件与指令');
 assert.equal(await page.locator('#editor').getAttribute('readonly'),'');
 assert.notEqual(await page.locator('#editor').inputValue(),'这是尚未保存的应用指令。');
 assert.equal(await page.getByRole('button',{name:'保存所有修改'}).count(),0);
 await page.locator('#identity').selectOption('application');
 await page.getByRole('button',{name:'进入工程'}).click();
 await navigate(page,'文件与指令');
 assert.equal(await page.locator('#editor').inputValue(),'这是尚未保存的应用指令。');
 await page.getByRole('button',{name:'保存所有修改'}).click();
 await page.getByText('已提交工程版本',{exact:true}).waitFor();
 assert.equal(workbench.store.files(apps[0].id,'application')['instructions.md'],'这是尚未保存的应用指令。');
 await page.getByRole('button',{name:'全部应用',exact:false}).click();
 await page.getByLabel('应用名称').fill('第二个应用');
 await page.getByRole('button',{name:'创建空白应用'}).click();
 await page.getByRole('heading',{name:'第二个应用',exact:true}).waitFor();
 await navigate(page,'文件与指令');
 assert.notEqual(await page.locator('#editor').inputValue(),'这是尚未保存的应用指令。');
 await page.getByLabel('切换工程').selectOption(apps[0].id);
 await page.getByRole('heading',{name:'i豆福利助手',exact:true}).waitFor();
 await navigate(page,'文件与指令');
 assert.equal(await page.locator('#editor').inputValue(),'这是尚未保存的应用指令。');
 for(const width of [1280,1440,1920]){await page.setViewportSize({width,height:1000});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}`);}
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'/tmp/workbench-pc-entry.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await page.evaluate(()=>localStorage.setItem('openjiuwen-workbench-live-ui-build','newer-page'));
 await page.locator('#editor').fill('过期页面不能提交');
 await page.getByRole('button',{name:'保存所有修改'}).click();
 await page.getByText('当前页面已过期，请保留草稿并刷新后操作',{exact:true}).waitFor();
 assert.equal(workbench.store.files(apps[0].id,'application')['instructions.md'],'这是尚未保存的应用指令。');
});
