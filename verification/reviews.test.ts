import {checkedRelease} from './fixtures/checked-release.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { ProjectStore } from '../workbench-server/projects.js';
import { ReviewManager } from '../workbench-server/reviews.js';
import { readTree } from '../workbench-server/files.js';
test('saved revision checks and technical candidates remain immutable and become stale after edits', t => {
    const root = mkdtempSync(join(tmpdir(), 'workbench-review-')), store = new ProjectStore(root);
    t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
    const template = store.seedTemplate(readTree('templates/moa')), release = checkedRelease(store,template.id, 'platform', '1.0.0'), p = store.createApplication(release.id, '检查应用', 'application');
    const reviews = new ReviewManager(store);
    const failed = reviews.check(p.id, 'application');
    assert.equal(failed.passed, false);
    assert.ok(failed.items.some((i: any) => i.code === 'BUSINESS_SCOPE' && !i.passed));
    const files = readTree('examples/idou'), saved = store.save(p.id, 'application', p.head, files);
    const valid = reviews.check(p.id, 'application');
    assert.equal(valid.head, saved.head);
    assert.equal(valid.passed, true);
    assert.equal(valid.business, 'not-verified');
    const candidate = reviews.candidate(p.id, 'application', valid.id);
    assert.equal(candidate.head, saved.head);
    assert.equal(candidate.verification, 'structural-only');
    assert.throws(() => reviews.candidate(p.id, 'platform', valid.id));
    store.save(p.id, 'application', saved.head, { 'instructions.md': files['instructions.md'] + '\n编辑后的新版本' });
    assert.equal(reviews.list(p.id, 'application')[0].stale, true);
    assert.equal(reviews.candidates(p.id, 'application')[0].head, candidate.head);
    assert.throws(() => reviews.candidate(p.id, 'application', valid.id));
});
test('unsupported assembly drafts and invalid references block checks; guidance/routing examples are validated', t => {
    const root = mkdtempSync(join(tmpdir(), 'workbench-review-')), store = new ProjectStore(root);
    t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
    const template = store.seedTemplate(readTree('templates/moa')), release = checkedRelease(store,template.id, 'platform', '1.0.0'), p = store.createApplication(release.id, '检查应用', 'application'), files = readTree('examples/idou');
    const d = JSON.parse(files['application.json']);
    d.capabilities.push({ id: 'new-api', type: 'tool', status: 'draft', execution: 'HTTP' });
    files['application.json'] = JSON.stringify(d);
    store.save(p.id, 'application', p.head, files);
    const manager = new ReviewManager(store), report = manager.check(p.id, 'application');
    assert.equal(report.passed, false);
    assert.ok(report.items.some((i: any) => i.code === 'ASSEMBLY_READY' && !i.passed));
    assert.throws(() => manager.candidate(p.id, 'application', report.id));
    assert.ok(manager.activity(p.id, 'application').some((i: any) => i.kind === 'commit'));
    assert.ok(manager.activity(p.id, 'platform').some((i: any) => i.kind === 'check'));
});
